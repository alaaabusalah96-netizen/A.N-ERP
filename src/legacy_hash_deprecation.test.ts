import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { getLegacyHashDeprecationPolicy, legacyHashPassword, legacySinglePassHashPassword, legacyStretchedHashPassword1000, hashPasswordPBKDF2_210k } from './lib/server_hash';

/**
 * Phase 4.1 (Part 2): Legacy Password Hash Deprecation & Sunset Enforcement Policy Unit Tests
 *
 * Validates:
 * 1. Policy metadata (announcementDate, sunsetDate, deprecated functions, target algorithm).
 * 2. Grace Period mode (ENFORCE_LEGACY_HASH_SUNSET != 'true'):
 *    - Legacy SHA-256 hashes are accepted for smooth auto-migration to PBKDF2 210,000 iterations.
 * 3. Sunset Enforced mode (ENFORCE_LEGACY_HASH_SUNSET = 'true'):
 *    - Legacy SHA-256 hashes are rejected with bilingual instructions to use Forgot Password OTP.
 *    - Upgraded PBKDF2 210,000 iteration hashes continue to authenticate normally.
 */

describe('Phase 4.1 Part 2: Legacy Password Hash Deprecation & Sunset Policy Tests', () => {
  const originalEnv = process.env.ENFORCE_LEGACY_HASH_SUNSET;

  afterEach(() => {
    if (originalEnv === undefined) {
      delete process.env.ENFORCE_LEGACY_HASH_SUNSET;
    } else {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = originalEnv;
    }
  });

  describe('1. Deprecation Policy Metadata Verification', () => {
    it('should return correct announcementDate, sunsetDate, and target PBKDF2 algorithm', () => {
      delete process.env.ENFORCE_LEGACY_HASH_SUNSET;
      const policy = getLegacyHashDeprecationPolicy();

      expect(policy.announcementDate).toBe('2026-08-01');
      expect(policy.sunsetDate).toBe('2027-02-01');
      expect(policy.targetAlgorithm).toContain('PBKDF2-HMAC-SHA256');
      expect(policy.targetPepperVersion).toBe(2);
      expect(policy.deprecatedHashFunctions).toContain('legacyHashPassword');
      expect(policy.deprecatedHashFunctions).toContain('legacySinglePassHashPassword');
      expect(policy.deprecatedHashFunctions).toContain('legacyStretchedHashPassword1000');
      expect(policy.deprecatedPepperVersions).toEqual([1, 3]);
    });

    it('should report gracePeriodActive = true when ENFORCE_LEGACY_HASH_SUNSET is not set to true', () => {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = 'false';
      const policy = getLegacyHashDeprecationPolicy();

      expect(policy.enforceSunset).toBe(false);
      expect(policy.gracePeriodActive).toBe(true);
      expect(policy.messageAr).toContain('فترة الهجرة التلقائية نشطة');
      expect(policy.messageEn).toContain('Auto-migration grace period active');
    });

    it('should report enforceSunset = true and provide Forgot Password guidance when ENFORCE_LEGACY_HASH_SUNSET=true', () => {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = 'true';
      const policy = getLegacyHashDeprecationPolicy();

      expect(policy.enforceSunset).toBe(true);
      expect(policy.gracePeriodActive).toBe(false);
      expect(policy.messageAr).toContain('انتهت صلاحية تشفير كلمة المرور القديم');
      expect(policy.messageEn).toContain('Legacy password encryption (SHA-256) has expired');
    });
  });

  describe('2. Legacy Hash Identification & Sunset Evaluation Logic', () => {
    const testPassword = 'SecurePassword!2026';
    const testSalt = 'salt_user_100';

    it('should identify legacy SHA-256 hashes generated by deprecated functions', () => {
      const hash1k = legacyStretchedHashPassword1000(testPassword, testSalt);
      const hashSingle = legacySinglePassHashPassword(testPassword, testSalt);
      const hashLegacy = legacyHashPassword(testPassword, testSalt);
      const pbkdf2Hash = hashPasswordPBKDF2_210k(testPassword, testSalt, 2);

      expect(hash1k).not.toBe(pbkdf2Hash);
      expect(hashSingle).not.toBe(pbkdf2Hash);
      expect(hashLegacy).not.toBe(pbkdf2Hash);
      expect(pbkdf2Hash.length).toBeGreaterThan(60);
    });

    it('should allow legacy hash match during grace period for auto-migration', () => {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = 'false';
      const policy = getLegacyHashDeprecationPolicy();
      const legacyStoredHash = legacyStretchedHashPassword1000(testPassword, testSalt);

      const isLegacyMatch = legacyStoredHash === legacyStretchedHashPassword1000(testPassword, testSalt);
      expect(isLegacyMatch).toBe(true);
      expect(policy.enforceSunset).toBe(false);
    });

    it('should reject legacy-only hash matches when ENFORCE_LEGACY_HASH_SUNSET is true', () => {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = 'true';
      const policy = getLegacyHashDeprecationPolicy();
      const legacyStoredHash = legacyHashPassword(testPassword, testSalt);

      const isLegacyMatch = legacyStoredHash === legacyHashPassword(testPassword, testSalt);
      const isPBKDF2Match = legacyStoredHash === hashPasswordPBKDF2_210k(testPassword, testSalt, 2);

      expect(isLegacyMatch).toBe(true);
      expect(isPBKDF2Match).toBe(false);
      expect(policy.enforceSunset).toBe(true);
      // In server.ts, when isLegacyMatch && !isPBKDF2Match && policy.enforceSunset => returns 426 LEGACY_HASH_SUNSET_EXPIRED
    });

    it('should always accept PBKDF2 210,000 iteration hashes even when sunset is enforced', () => {
      process.env.ENFORCE_LEGACY_HASH_SUNSET = 'true';
      const pbkdf2StoredHash = hashPasswordPBKDF2_210k(testPassword, testSalt, 2);

      const isPBKDF2Match = pbkdf2StoredHash === hashPasswordPBKDF2_210k(testPassword, testSalt, 2);
      expect(isPBKDF2Match).toBe(true);
    });
  });
});
