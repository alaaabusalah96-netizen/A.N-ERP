      triggerToast(`${l.successCreated} | #${finalVoucherNo}`);
      
      // Auto clear states
      setVoucherNo('');
      setRecipientName('');
      setReceivedBy('');
      setSelectedTxIds([]);
      setValidationError('');
      setSelectedTx(null); // Clear parent pre-select

      // Reload lists
      loadData();

      // Auto-open print preview modal for immediate print workflow!
